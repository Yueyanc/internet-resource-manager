export function findAccountPreset(key: string): AccountPreset | undefined {
  return key ? presetByKey.get(key) : undefined;
}

export function resolveAccountPreset(value: Pick<Account, 'presetKey' | 'platform'>): AccountPreset | undefined {
  if (value.presetKey) {
    const direct = presetByKey.get(value.presetKey);
    if (direct) return direct;
  }
  const text = value.platform.trim();
  if (!text) return undefined;
  const lower = text.toLowerCase();
  const exact = accountPresets.find(preset => preset.platform.zh.toLowerCase() === lower || preset.platform.en.toLowerCase() === lower);
  if (exact) return exact;
  for (const matcher of fallbackMatchers) {
    if (matcher.patterns.some(pattern => pattern.test(text))) {
      return presetByKey.get(matcher.key);
    }
  }
  return undefined;
}

export function filterAccountPresets(query: string, group: AccountPresetGroup): AccountPreset[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return group === 'popular'
      ? accountPresets.filter(item => item.popular)
      : accountPresets.filter(item => item.group === group);
  }
  return accountPresets.filter(item =>
    item.platform.zh.toLowerCase().includes(q)
    || item.platform.en.toLowerCase().includes(q)
    || item.subtitle.zh.toLowerCase().includes(q)
    || item.subtitle.en.toLowerCase().includes(q)
    || item.keywords.some(kw => kw.toLowerCase().includes(q)),
  );
}
